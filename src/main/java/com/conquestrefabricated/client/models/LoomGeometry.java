package com.conquestrefabricated.client.models;

import com.google.gson.JsonArray;
import com.google.gson.JsonDeserializationContext;
import com.google.gson.JsonObject;
import com.google.gson.JsonParseException;
import java.util.function.Function;
import net.minecraft.client.renderer.block.model.ItemOverrides;
import net.minecraft.client.renderer.texture.TextureAtlasSprite;
import net.minecraft.client.resources.model.BakedModel;
import net.minecraft.client.resources.model.Material;
import net.minecraft.client.resources.model.ModelBaker;
import net.minecraft.client.resources.model.ModelState;
import net.minecraft.client.resources.model.UnbakedModel;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.util.GsonHelper;
import net.minecraft.world.inventory.InventoryMenu;
import net.neoforged.neoforge.client.model.geometry.IGeometryBakingContext;
import net.neoforged.neoforge.client.model.geometry.IGeometryLoader;
import net.neoforged.neoforge.client.model.geometry.IUnbakedGeometry;
import org.joml.Vector3f;

/**
 * Replaces LoomUnbakedModel + the old TranslatedModelLoaderMixin. A model JSON with
 * {"loader":"conquest:loom","base":..,"extra":..,"size":"small|medium|large","translation":[x,y,z]}
 * is baked into a LoomBakedModel. Rotation comes from the blockstate variant's "y".
 * The JSON files are generated by tools/gen_loom_models.py.
 */
public class LoomGeometry implements IUnbakedGeometry<LoomGeometry> {
   public static final ResourceLocation LOADER_ID = ResourceLocation.fromNamespaceAndPath("conquest", "loom");
   private static final String[] TEXTURE_NAMES = new String[]{
      "loom_weave_white", "loom_weave_red", "loom_weave_black", "loom_weave_gray", "loom_weave_light_gray",
      "loom_weave_white", "loom_weave_brown", "loom_weave_yellow", "loom_weave_orange", "loom_weave_pink",
      "loom_weave_magenta", "loom_weave_purple", "loom_weave_blue", "loom_weave_light_blue", "loom_weave_cyan",
      "loom_weave_green", "loom_weave_lime", "loom_weave_baotao", "loom_weave_berber", "loom_weave_black_persian",
      "loom_weave_blue_nain", "loom_weave_brown_oriental", "loom_weave_celtic_knot", "loom_weave_kashmiri",
      "loom_weave_kazakh", "loom_weave_kilim", "loom_weave_nahavand", "loom_weave_red_and_blue_sarouk",
      "loom_weave_red_oriental", "loom_weave_red_pazyryk", "loom_weave_shirishabad", "loom_weave_william_morris",
      "loom_weave_yellow_red_persian"
   };

   private final ResourceLocation base;
   private final ResourceLocation extra;
   private final String size;
   private final Vector3f translation;

   public LoomGeometry(ResourceLocation base, ResourceLocation extra, String size, Vector3f translation) {
      this.base = base;
      this.extra = extra;
      this.size = size;
      this.translation = translation;
   }

   @Override
   public void resolveParents(Function<ResourceLocation, UnbakedModel> modelGetter, IGeometryBakingContext context) {
      modelGetter.apply(this.base).resolveParents(modelGetter);
      modelGetter.apply(this.extra).resolveParents(modelGetter);
   }

   @Override
   public BakedModel bake(IGeometryBakingContext context, ModelBaker baker, Function<Material, TextureAtlasSprite> spriteGetter, ModelState modelState, ItemOverrides overrides) {
      ModelState state = this.translation == null ? modelState : new LoomTranslationBakeSettings(modelState, this.translation);
      BakedModel baseBaked = baker.bake(this.base, state, spriteGetter);
      BakedModel extraBaked = baker.bake(this.extra, state, spriteGetter);
      TextureAtlasSprite[] sprites = new TextureAtlasSprite[33];
      for (int i = 0; i < TEXTURE_NAMES.length; i++) {
         sprites[i] = spriteGetter.apply(new Material(
            InventoryMenu.BLOCK_ATLAS,
            ResourceLocation.fromNamespaceAndPath("conquest", "block/7_tools/3_utility/loom/weaves/" + this.size + "/" + TEXTURE_NAMES[i])));
      }
      return new LoomBakedModel(baseBaked, extraBaked, sprites);
   }

   public static class Loader implements IGeometryLoader<LoomGeometry> {
      @Override
      public LoomGeometry read(JsonObject json, JsonDeserializationContext ctx) throws JsonParseException {
         ResourceLocation base = ResourceLocation.parse(GsonHelper.getAsString(json, "base"));
         ResourceLocation extra = ResourceLocation.parse(GsonHelper.getAsString(json, "extra"));
         String size = GsonHelper.getAsString(json, "size");
         Vector3f translation = null;
         if (json.has("translation")) {
            JsonArray a = GsonHelper.getAsJsonArray(json, "translation");
            translation = new Vector3f(a.get(0).getAsFloat(), a.get(1).getAsFloat(), a.get(2).getAsFloat());
         }
         return new LoomGeometry(base, extra, size, translation);
      }
   }
}
